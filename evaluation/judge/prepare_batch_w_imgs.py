"""
prepare_batch.py

Reads a predictions JSONL and the google/docci HuggingFace dataset, pairs each
prediction with the matching image (keyed by example_id) and its reference
description, converts the image to base64, and writes an OpenAI Batch API
JSONL file ready for submission.

The judge receives the image, the DOCCI reference description, and the
candidate caption, scoring it across 5 DOCCI dimensions plus Basque language quality.

DOCCI fields used:
  - 'example_id'  : unique string key (e.g. "test_01535")
  - 'image'       : PIL image
  - 'description' : gold reference description

Predictions JSONL fields expected:
  - 'idx'         : row index (for logging)
  - 'question_id' : matches DOCCI's example_id
  - 'prediction'  : the model-generated caption to evaluate
"""

import argparse
import base64
import io
import json
import sys
from pathlib import Path

from datasets import load_dataset

JUDGE_PROMPT_TEMPLATE = """\
You are an expert evaluator for image captioning models. You will be given:
- A REFERENCE DESCRIPTION: a detailed, human-annotated ground-truth description of an image
- A CANDIDATE CAPTION: a caption generated by a model for the same image

Your task is to score the candidate caption across 5 dimensions that reflect DOCCI's key annotation criteria. For each dimension, assign a score from 1-5 and provide a one-sentence justification.

---

REFERENCE DESCRIPTION:
{reference_description}

CANDIDATE CAPTION:
{candidate_caption}

---

## Evaluation Dimensions

### 1. Object & Attribute Coverage (1-5)
Does the caption mention the main objects, their colors, sizes, shapes, textures, and other visual attributes described in the reference?
- 5: All key objects and their attributes are accurately captured
- 3: Main objects present but attributes missing or imprecise
- 1: Major objects or attributes absent

### 2. Spatial Relations (1-5)
Does the caption accurately describe positional and directional relationships between objects (e.g., left/right, in front of, on top of, facing toward)?
- 5: Spatial layout matches reference fully and precisely
- 3: Some spatial relations mentioned but incomplete or vague
- 1: Spatial relations largely ignored or incorrect

### 3. Counting & Quantity (1-5)
Are quantities of countable elements (people, objects, items) correctly stated?
- 5: All quantities match the reference exactly
- 3: Some quantities present but with minor errors
- 1: Quantities absent or significantly wrong

### 4. Text & Fine-grained Detail (1-5)
Does the caption capture fine-grained details such as text visible in the scene, logos, patterns, lighting conditions, or subtle distinguishing features?
- 5: Fine-grained details and any visible text accurately reproduced
- 3: Some fine-grained detail present, but text or subtle cues missed
- 1: Fine-grained details largely absent

### 5. Factual Accuracy / Hallucination (1-5)
Does the caption avoid stating things that are not present or incorrect relative to the reference?
- 5: No hallucinated or contradicted content
- 3: Minor additions or inaccuracies not supported by reference
- 1: Clear hallucinations or factual contradictions


---

## Output Format

Respond with a JSON object only, no other text:
{{
  "object_attribute_coverage": {{"score": <1-5>, "reason": "<feedback>"}},
  "spatial_relations":         {{"score": <1-5>, "reason": "<feedback>"}},
  "counting_quantity":         {{"score": <1-5>, "reason": "<feedback>"}},
  "text_fine_grained_detail":  {{"score": <1-5>, "reason": "<feedback>"}},
  "factual_accuracy":          {{"score": <1-5>, "reason": "<feedback>"}},
  "overall_score":             <average of the 5 scores, rounded to 1 decimal>,
}}"""

JUDGE_SCHEMA = {
    "type": "json_schema",
    "json_schema": {
        "name": "judge_output",
        "strict": True,
        "schema": {
            "type": "object",
            "properties": {
                "object_attribute_coverage": {
                    "type": "object",
                    "properties": {
                        "score":  {"type": "integer", "enum": [1, 2, 3, 4, 5]},
                        "reason": {"type": "string"},
                    },
                    "required": ["score", "reason"],
                    "additionalProperties": False,
                },
                "spatial_relations": {
                    "type": "object",
                    "properties": {
                        "score":  {"type": "integer", "enum": [1, 2, 3, 4, 5]},
                        "reason": {"type": "string"},
                    },
                    "required": ["score", "reason"],
                    "additionalProperties": False,
                },
                "counting_quantity": {
                    "type": "object",
                    "properties": {
                        "score":  {"type": "integer", "enum": [1, 2, 3, 4, 5]},
                        "reason": {"type": "string"},
                    },
                    "required": ["score", "reason"],
                    "additionalProperties": False,
                },
                "text_fine_grained_detail": {
                    "type": "object",
                    "properties": {
                        "score":  {"type": "integer", "enum": [1, 2, 3, 4, 5]},
                        "reason": {"type": "string"},
                    },
                    "required": ["score", "reason"],
                    "additionalProperties": False,
                },
                "factual_accuracy": {
                    "type": "object",
                    "properties": {
                        "score":  {"type": "integer", "enum": [1, 2, 3, 4, 5]},
                        "reason": {"type": "string"},
                    },
                    "required": ["score", "reason"],
                    "additionalProperties": False,
                },
                "overall_score": {"type": "number"},
            },
            "required": [
                "object_attribute_coverage",
                "spatial_relations",
                "counting_quantity",
                "text_fine_grained_detail",
                "factual_accuracy",
                "overall_score",
                "basque_quality",
            ],
            "additionalProperties": False,
        },
    },
}


def pil_to_base64(pil_image, format: str = "JPEG") -> tuple[str, str]:
    """
    Converts a PIL Image to a base64-encoded string.
    Returns (base64_string, media_type), e.g. ("...", "image/jpeg").
    PNG is used as fallback for images with transparency (RGBA).
    """
    if pil_image.mode in ("RGBA", "LA") or (pil_image.mode == "P" and "transparency" in pil_image.info):
        format = "PNG"
    media_type = f"image/{format.lower()}"
    buffer = io.BytesIO()
    pil_image.save(buffer, format=format)
    b64 = base64.b64encode(buffer.getvalue()).decode("utf-8")
    return b64, media_type


def load_hf_data(split: str, dataset_name: str) -> dict[str, dict]:
    """
    Returns a dict mapping example_id -> {"image": (b64, media_type), "description": str}.
    Loads PIL images and reference descriptions from the DOCCI HuggingFace dataset.
    The example_id in DOCCI is matched against question_id in the predictions JSONL.
    """
    print(f"Loading {dataset_name} (split={split}) from HuggingFace...")
    ds = load_dataset(dataset_name, split=split)

    data_map: dict[str, dict] = {}
    for row in ds:
        example_id  = row.get("example_id")
        pil_image   = row.get("image")
        description = row.get("description")
        if example_id is not None and pil_image is not None:
            data_map[str(example_id)] = {
                "image":       pil_to_base64(pil_image),
                "description": description or "",
            }

    print(f"  Loaded {len(data_map)} entries.")
    return data_map


def build_batch_request(custom_id: str, model: str, b64_image: str, media_type: str, prompt: str) -> dict:
    data_uri = f"data:{media_type};base64,{b64_image}"
    return {
        "custom_id": custom_id,
        "method": "POST",
        "url": "/v1/chat/completions",
        "body": {
            "model": model,
            "max_completion_tokens": 1500,
            "response_format": JUDGE_SCHEMA,
            "messages": [
                {
                    "role": "user",
                    "content": [
                        {
                            "type": "image_url",
                            "image_url": {"url": data_uri},
                        },
                        {
                            "type": "text",
                            "text": prompt,
                        },
                    ],
                }
            ],
        },
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--predictions_file", required=True,          help="Path to the predictions JSONL file.")
    parser.add_argument("--batch_file",        required=True,          help="Output path for the OpenAI batch JSONL.")
    parser.add_argument("--model_name",        default="gpt-4o",      help="OpenAI model to use for judging.")
    parser.add_argument("--hf_split",          default="test",         help="HuggingFace dataset split to load (default: test).")
    parser.add_argument("--hf_dataset",        default="google/docci", help="HuggingFace dataset name (default: google/docci).")

    args = parser.parse_args()

    predictions_path = Path(args.predictions_file)
    if not predictions_path.exists():
        sys.exit(f"ERROR: predictions file not found: {predictions_path}")

    # Load PIL images and reference descriptions from DOCCI, keyed by example_id
    data_map = load_hf_data(args.hf_split, args.hf_dataset)

    # Read predictions
    predictions = []
    with open(predictions_path) as f:
        for lineno, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                predictions.append(json.loads(line))
            except json.JSONDecodeError as e:
                print(f"  WARNING: skipping malformed line {lineno}: {e}")

    print(f"Read {len(predictions)} predictions from {predictions_path}")

    # Build batch requests
    batch_path = Path(args.batch_file)
    batch_path.parent.mkdir(parents=True, exist_ok=True)

    skipped = 0
    written = 0
    with open(batch_path, "w") as out:
        for entry in predictions:
            idx         = entry.get("idx")
            question_id = entry.get("question_id")
            prediction  = entry.get("prediction", "").strip()

            if question_id is None:
                print(f"  WARNING: missing question_id at idx={idx}, skipping.")
                skipped += 1
                continue

            row = data_map.get(str(question_id))
            if row is None:
                print(f"  WARNING: no data found for question_id={question_id} (idx={idx}), skipping.")
                skipped += 1
                continue

            if not prediction:
                print(f"  WARNING: empty prediction for question_id={question_id} (idx={idx}), skipping.")
                skipped += 1
                continue

            b64_image, media_type = row["image"]
            reference_description = row["description"]

            prompt = JUDGE_PROMPT_TEMPLATE.format(
                reference_description=reference_description,
                candidate_caption=prediction,
            )
            custom_id = f"judge-idx{idx}-{question_id}"
            request   = build_batch_request(custom_id, args.model_name, b64_image, media_type, prompt)
            out.write(json.dumps(request, ensure_ascii=False) + "\n")
            written += 1

    print(f"Batch file written to {batch_path}")
    print(f"  Requests written : {written}")
    print(f"  Entries skipped  : {skipped}")


if __name__ == "__main__":
    main()